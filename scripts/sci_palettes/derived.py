@lru_cache(maxsize=1)
def _apps() -> dict:
    if not os.path.exists(_APP_FILE):
        raise FileNotFoundError(
            f"application data missing: {_APP_FILE}\n"
            "regenerate it with: python tools/gen_applications.py")
    with open(_APP_FILE, encoding="utf-8") as fh:
        return json.load(fh)


def _app_key(field: str) -> str:
    key = APP_ALIASES.get(field) or APP_ALIASES.get(field.strip().lower())
    if key:
        return key
    raise KeyError(f"unknown field {field!r}; use one of "
                   f"{', '.join(sorted(set(APP_ALIASES.values())))} "
                   f"(Chinese names work: 临床 / 数据库 / 基础 / 通用)")


def profiles() -> dict[str, dict]:
    """The four application profiles with their scoring criteria."""
    return _apps()["profiles"]


def applications(name: str) -> dict:
    """Suitability of one palette for each field: scores, pass/fail, metrics.

    >>> sp.applications("burgundy-clin-hi")["scores"]
    {'clinical': 82, 'database': 65, 'basic': 92, 'general': 90}
    """
    pid = resolve(name)
    rec = _apps()["palettes"].get(pid)
    if rec is None:
        raise KeyError(f"no application record for {pid!r}")
    return rec


def application(name: str) -> str:
    """The field a palette suits best."""
    return applications(name)["primary"]


def anchors() -> dict[str, dict]:
    """The six anchor palettes: values transcribed from the reference figures.

    Called anchors rather than originals on purpose - the reference figures hold
    the original colours, and every value in this library is derived from them.
    """
    return {k: dict(v) for k, v in PALETTES.items()}


def variants() -> dict[str, dict]:
    """The generated palettes keyed by id (:func:`all_palettes` returns both)."""
    return {pid: info for pid, info in all_palettes().items()
            if pid not in PALETTES}


def suggest_for(field: str, *, n: int = 10, require_fit: bool = False,
                family_name: str | None = None,
                include_anchors: bool = True) -> list[dict]:
    """Rank palettes for a research field.

    ``field`` accepts ``"clinical"``, ``"database"``, ``"basic"``, ``"general"``
    or the Chinese words 临床 / 数据库 / 基础 / 通用.

    A palette can score well for a field without being a hard "fit" for it, so
    the ranking is by score and the ``fits`` flag tells you whether it cleared
    every requirement of that field. ``require_fit=True`` drops the rest.
    """
    key = _app_key(field)
    pal = _apps()["palettes"]
    rows = []
    for pid, rec in pal.items():
        if not include_anchors and pid in PALETTES:
            continue
        if family_name:
            info = all_palettes()[pid]
            if info.get("family") != family_name and info.get("base") != family_name:
                continue
        fits = bool(rec["fit"][key])
        if require_fit and not fits:
            continue
        info = all_palettes()[pid]
        m = rec["metrics"]
        rows.append({
            "id": pid,
            "score": rec["scores"][key],
            "fits": fits,
            "name_zh": info["name_zh"],
            "name_en": info["name_en"],
            "hex": info["hex"],
            "derived": pid not in PALETTES,
            "metrics": m,
            "why": _why(key, m, fits),
        })
    rows.sort(key=lambda r: (-r["score"], not r["fits"], r["id"]))
    return rows[:n]


def _why(key: str, m: dict, fits: bool) -> str:
    """One-line reason, so a recommendation can be checked rather than trusted."""
    bits = []
    if key == "clinical":
        bits.append(f"colour-vision separation {m['cvd5']:.1f} on the best 5")
        bits.append(f"{m['dark']} dark member(s) for labels")
    elif key == "database":
        bits.append(f"pairwise separation {m['min5']:.1f} on the best 5")
        bits.append(f"hue spread {m['hue_spread']:.0f} deg for many categories")
    elif key == "basic":
        bits.append(f"lightness span {m['span8']:.2f} for greyscale printing")
        bits.append(f"separation {m['min5']:.1f} on the best 5")
    else:
        bits.append(f"span {m['span8']:.2f}, separation {m['min5']:.1f}")
    if not fits:
        bits.append("below the strict bar for this field - usable, but check "
                    "the audit before relying on it")
    return "; ".join(bits)


def stats() -> dict:
    """Summary of the whole library, anchor plus generated."""
    data = _load()
    scores = [r["score"] for r in data["palettes"]]
    apps = _apps()["palettes"]
    fits = {k: sum(1 for v in apps.values() if v["fit"][k])
            for k in profiles()}
    return {
        "anchors": len(PALETTES),
        "variants": len(data["palettes"]),
        "total": len(PALETTES) + len(data["palettes"]),
        # kept so code written against v2 keeps working
        "anchor": len(PALETTES),
        "derived": len(data["palettes"]),
        "families": families(),
        "per_base": bases(),
        "score_min": min(scores),
        "score_mean": round(sum(scores) / len(scores), 1),
        "score_max": max(scores),
        "quality_gate": data["quality_gate"],
        "fit_by_field": fits,
    }
