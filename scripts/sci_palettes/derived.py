# -*- coding: utf-8 -*-
"""Access to the generated palette library.

The six anchor palettes (``data.py``) have hex values transcribed from the
reference figures. This module exposes the 178 variants generated from them
(hue rotations, temperature drift, chroma and contrast changes, monochrome
versions, diverging scales and cross-palette blends), each audited and scored,
so a figure can be tuned without leaving the family.

Generated by ``tools/gen_derived_palettes.py``; the data lives in
``derived.json`` next to this file and is loaded once, on first use.
"""

from __future__ import annotations

import json
import os
from functools import lru_cache

from .core import delta_e, luminance, resolve
from .data import PALETTES

__all__ = [
    "all_palettes", "derived_names", "get", "search", "recommend", "family",
    "families", "bases", "stats", "best_for", "random_palette", "quality",
    "applications", "profiles", "suggest_for", "application",
    "anchors", "variants",
]

_DATA_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "derived.json")
_APP_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), "applications.json")

FAMILY_LABELS = {
    "hue_rotate": "hue rotation - the same scheme at a different hue angle",
    "temperature": "warm/cool drift - the scheme moved toward orange or cyan",
    "chroma": "saturation - muted, softened or intensified",
    "contrast": "contrast - a lifted (light) or deepened (dark) lightness ramp",
    "complement": "complementary - every hue moved to its opposite",
    "monochrome": "single hue family, lightness only",
    "blend": "two anchor palettes mixed in LCh",
    "clinical": "built for survival curves, forest plots and adverse-event panels",
    "database": "built for many cohorts, centres or sites on one axis",
    "basic": "built for greyscale-safe basic-research panels",
    "diverging": "symmetric scale for reference ranges and fold changes",
}

# Which single alias each field accepts, in the languages people type.
APP_ALIASES = {
    "clinical": "clinical", "临床": "clinical", "临床研究": "clinical",
    "survival": "clinical", "km": "clinical", "生存": "clinical",
    "database": "database", "数据库": "database", "队列": "database",
    "registry": "database", "ehr": "database", "cohort": "database",
    "db": "database", "多中心": "database",
    "basic": "basic", "基础": "basic", "基础科研": "basic", "实验": "basic",
    "bench": "basic", "materials": "basic",
    "general": "general", "通用": "general", "跨学科": "general",
}


@lru_cache(maxsize=1)
def _load() -> dict:
    if not os.path.exists(_DATA_FILE):
        raise FileNotFoundError(
            f"derived palette data missing: {_DATA_FILE}\n"
            "regenerate it with: python tools/gen_derived_palettes.py")
    with open(_DATA_FILE, encoding="utf-8") as fh:
        return json.load(fh)


@lru_cache(maxsize=1)
def _by_id() -> dict[str, dict]:
    return {r["id"]: r for r in _load()["palettes"]}


def derived_names() -> list[str]:
    """Ids of every generated palette, in the data file's order."""
    return [r["id"] for r in _load()["palettes"]]


def all_palettes(*, derived: bool = True) -> dict[str, dict]:
    """The six anchor palettes, optionally merged with every variant.

    Returns the same shape as :data:`sci_palettes.data.PALETTES`, plus an extra
    ``"base"`` key on derived entries naming their parent palette.
    """
    out = {k: dict(v) for k, v in PALETTES.items()}
    if derived:
        for pid, rec in _by_id().items():
            out[pid] = {
                "name_zh": rec["name_zh"],
                "name_en": rec["name_en"],
                "subtitle_zh": FAMILY_LABELS.get(rec["family"], rec["family"]),
                "subtitle_en": rec["note"],
                "vibe": rec["note"],
                "base": rec["base"],
                "family": rec["family"],
                "transform": rec["transform"],
                "hex": list(rec["hex"]),
                "roles": [f"member {i}" for i in range(1, len(rec["hex"]) + 1)],
                "audit": rec["audit"],
                "score": rec["score"],
            }
    return out


def get(name: str) -> dict:
    """Metadata for any palette, anchor or derived."""
    pid = resolve(name)
    if pid in PALETTES:
        info = dict(PALETTES[pid])
        info["id"] = pid
        info["derived"] = False
        return info
    rec = _by_id()[pid]
    info = all_palettes()[pid]
    info["id"] = pid
    info["derived"] = True
    return info


def quality(name: str) -> dict:
    """The audit record of a palette (derived palettes only)."""
    pid = resolve(name)
    if pid in _by_id():
        return _by_id()[pid]["audit"]
    cols = PALETTES[pid]["hex"]
    from .core import check
    return check(pid)


def families() -> dict[str, int]:
    """Family name -> how many variants it contains."""
    counts: dict[str, int] = {}
    for r in _load()["palettes"]:
        counts[r["family"]] = counts.get(r["family"], 0) + 1
    return dict(sorted(counts.items(), key=lambda kv: -kv[1]))


def bases() -> dict[str, int]:
    """Parent palette -> how many variants it has."""
    counts: dict[str, int] = {}
    for r in _load()["palettes"]:
        counts[r["base"]] = counts.get(r["base"], 0) + 1
    return counts


def family(name: str, *, min_score: int = 0, sort_by_score: bool = True) -> list[str]:
    """Ids in one family, or every variant of one parent palette.

    ``family("hue_rotate")`` and ``family("glacier")`` both work, because both
    are keys in the generated index.
    """
    key = name if name in _load()["index"] else (resolve(name) if _is_base(name) else name)
    if key not in _load()["index"]:
        raise KeyError(f"no family or base palette named {name!r}; "
                       f"known families: {', '.join(families())}; "
                       f"known bases: {', '.join(PALETTES)}")
    ids = list(_load()["index"][key])
    if min_score:
        ids = [i for i in ids if _by_id()[i]["score"] >= min_score]
    if sort_by_score:
        ids.sort(key=lambda i: -_by_id()[i]["score"])
    return ids


def _is_base(name: str) -> bool:
    try:
        return resolve(name) in PALETTES
    except KeyError:
        return False


def search(colour: str, *, limit: int = 10, min_score: int = 55,
           exclude_bases: bool = False, tolerance: float = 26.0) -> list[dict]:
    """Palettes containing a colour close to ``colour``.

    Ranked by how well the palette covers the request, not by palette score
    alone: a palette with the colour in the middle of its ramp beats one where
    it is the palest member.
    """
    hits = []
    for pid, info in all_palettes().items():
        if exclude_bases and pid in PALETTES:
            continue
        score = info.get("score") or 0
        if pid not in PALETTES and score < min_score:
            continue
        dists = sorted((delta_e(colour, c), c) for c in info["hex"])
        d, closest = dists[0]
        if d > tolerance:
            continue
        lums = [luminance(c) for c in info["hex"]]
        # prefer palettes where the matched colour is not an extreme member
        pos = info["hex"].index(closest)
        centrality = 1.0 - abs(pos - (len(info["hex"]) - 1) / 2) / ((len(info["hex"]) - 1) / 2)
        rank = d / max(tolerance, 1e-6) - 0.25 * centrality
        hits.append({
            "id": pid,
            "closest": closest,
            "delta_e": round(d, 1),
            "position": pos + 1,
            "score": score,
            "name_zh": info["name_zh"],
            "hex": info["hex"],
            "lightness_span": round(max(lums) - min(lums), 3),
            "_rank": rank,
        })
    hits.sort(key=lambda h: (h["_rank"], -h["score"]))
    for h in hits:
        h.pop("_rank", None)
    return hits[:limit]


def recommend(field: str | None = None, *, n: int = 8, min_score: int = 70,
              family_name: str | None = None) -> list[dict]:
    """Highest-scoring palettes, optionally filtered by field or family."""
    pool = []
    for pid, info in all_palettes().items():
        if field:
            import re
            hay = " ".join(str(x) for x in (
                info.get("name_en", ""), info.get("name_zh", ""),
                info.get("subtitle_zh", ""), info.get("subtitle_en", ""),
                info.get("vibe", ""), pid)).lower()
            if not re.search(field.lower(), hay):
                continue
        if family_name and info.get("family") != family_name:
            continue
        score = info.get("score")
        if score is None:
            score = 85        # the anchor palettes are the reference
        if score < min_score:
            continue
        pool.append({"id": pid, "score": score, "name_zh": info["name_zh"],
                     "name_en": info["name_en"], "hex": info["hex"],
                     "family": info.get("family", "anchor"),
                     "base": info.get("base", pid)})
    pool.sort(key=lambda r: (-r["score"], r["base"]))
    return pool[:n]


def best_for(field: str, *, n: int = 3) -> list[dict]:
    """Convenience wrapper: top palettes for a field keyword."""
    return recommend(field, n=n, min_score=0)


def random_palette(seed=None, *, min_score: int = 60) -> str:
    """A reproducible random palette id, for exploring the library."""
    import random
    rng = random.Random(seed)
    pool = [r["id"] for r in _load()["palettes"] if r["score"] >= min_score]
    if not pool:
        raise ValueError(f"no derived palette scores >= {min_score}")
    return rng.choice(pool)


